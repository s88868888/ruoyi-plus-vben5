// ============================================================================
// 5. 偏好设置说明
// ============================================================================
//
// 用户可以在系统设置 > 外观 > 详情页设置 中调整以下参数：
//
// - 卡片圆角 (cardRadius): 0-32px
//   应用于所有卡片、输入框、按钮等元素的 border-radius
//
// - 内容字体大小 (fontSize): 12-20px
//   应用于表单标签、输入框、按钮等所有文本元素
//
// - 内容最大宽度 (contentWidth): 0-3840px
//   当前主要用于详情页，编辑页面中的抽屉/模态框有固定宽度，此参数不适用


// ============================================================================
// 6. 样式优先级
// ============================================================================
//
// 全局样式适配器使用 !important 确保偏好设置优先级最高，这样用户的偏好
// 设置总是会被应用，即使组件有其他样式定义。


// ============================================================================
// 7. 实时更新
// ============================================================================
//
// 所有样式都是响应式的。当用户在设置面板中修改偏好设置时，所有编辑页面
// 会立即更新，无需刷新页面。


// ============================================================================
// 8. 常见问题
// ============================================================================
//
// Q: 为什么我的编辑页面没有应用新的样式？
// A: 确保：
//    1. 已在 bootstrap.ts 中初始化了 setupEditPageStyleAdapter()
//    2. 浏览器控制台没有错误
//    3. 清除浏览器缓存并刷新页面
//
// Q: 我想为特定的编辑页面使用不同的样式怎么办？
// A: 可以在组件中覆盖全局样式，或者创建自定义的 composable
//
// Q: 抽屉/模态框的宽度能否根据偏好设置调整？
// A: 目前抽屉和模态框的宽度是固定的（如 w-[900px]），这是为了保持
//    良好的用户体验。如果需要调整，可以修改具体的组件。
